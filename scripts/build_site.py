"""Build the dashboard as a multi-file static site and zip it.

Splits dashboard/template.html into separate HTML, CSS, JavaScript and data
files so the dashboard can be uploaded to GitHub Pages (or any static host)
or opened straight from disk:

    site/
      index.html            page markup
      css/styles.css        all styling
      js/app.js             dashboard logic (filters, KPIs, charts, tables)
      js/vendor/chart.umd.js    Chart.js 4.4.1 (MIT)
      data/games.js         cleaned game data used by the dashboard
      data/games.csv        raw nflverse source file, for reference
      README.md, .nojekyll

The data ships as a .js file (not .json) so the page also works when opened
with a double-click: browsers block fetch() from file:// pages.

    python scripts/build_site.py      # writes site/ and dist/nfl-edge-dashboard.zip
"""
import json
import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

from build_dashboard import CHARTJS, TEMPLATE, payload  # noqa: E402

SITE = ROOT / "site"
ZIP = ROOT / "dist" / "nfl-edge-dashboard.zip"

README = """# NFL Edge dashboard

Interactive dashboard of NFL results against the closing betting line,
{first}–{last} ({games:,} completed games, data through {through}).

## Run it

- **On your computer:** unzip and double-click `index.html`. No internet,
  server or install needed.
- **On GitHub Pages:** upload the contents of this folder to the root of a
  repository (keep the folder structure), then in **Settings → Pages** choose
  **Deploy from a branch**, branch `main`, folder `/ (root)`. The site appears
  at `https://<your-user>.github.io/<repo>/` after a minute or two.

## Files

| Path | Contents |
|---|---|
| `index.html` | Page markup |
| `css/styles.css` | All styling, light and dark themes |
| `js/app.js` | Filters, KPIs, charts, tables and question answers |
| `js/vendor/chart.umd.js` | Chart.js 4.4.1 (MIT licence, see `js/vendor/chart.js-LICENSE.md`) |
| `data/games.js` | Cleaned game data the dashboard reads |
| `data/games.csv` | Raw nflverse source file, for reference |

Source data: nflverse `games.csv` (https://github.com/nflverse/nfldata).
Historical description only; not betting advice.
"""


def main() -> None:
    html = TEMPLATE.read_text(encoding="utf-8")

    css = re.search(r"<style>\n(.*?)</style>\n", html, re.S)
    js = re.search(r"<script>\nconst RAW = /\*__DATA__\*/null;\n(.*?)</script>\n", html, re.S)
    if not css or not js or "<script>/*__CHARTJS__*/</script>" not in html:
        raise SystemExit("template.html layout changed; update build_site.py")

    page = html.replace(css.group(0), '<link rel="stylesheet" href="css/styles.css">\n')
    page = page.replace(
        "<script>/*__CHARTJS__*/</script>\n",
        '<script src="js/vendor/chart.umd.js"></script>\n',
    )
    page = page.replace(
        js.group(0),
        '<script src="data/games.js"></script>\n<script src="js/app.js"></script>\n',
    )
    app = "const RAW = window.NFL_DATA;\n" + js.group(1)
    data = payload()

    if SITE.exists():
        shutil.rmtree(SITE)
    (SITE / "css").mkdir(parents=True)
    (SITE / "js" / "vendor").mkdir(parents=True)
    (SITE / "data").mkdir(parents=True)
    (SITE / "index.html").write_text(page, encoding="utf-8")
    (SITE / "css" / "styles.css").write_text(css.group(1), encoding="utf-8")
    (SITE / "js" / "app.js").write_text(app, encoding="utf-8")
    shutil.copy(CHARTJS, SITE / "js" / "vendor" / "chart.umd.js")
    shutil.copy(CHARTJS.parent / "chart.js-LICENSE.md", SITE / "js" / "vendor" / "chart.js-LICENSE.md")
    (SITE / "data" / "games.js").write_text(
        "// Generated by scripts/build_site.py from data/raw/games.csv. Do not edit by hand.\n"
        "window.NFL_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    shutil.copy(ROOT / "data" / "raw" / "games.csv", SITE / "data" / "games.csv")
    seasons = sorted({g[0] for g in data["games"]})
    (SITE / "README.md").write_text(
        README.format(first=seasons[0], last=seasons[-1], games=len(data["games"]), through=data["meta"]["lastGame"]),
        encoding="utf-8",
    )
    (SITE / ".nojekyll").write_text("", encoding="utf-8")  # serve files as-is on GitHub Pages

    ZIP.parent.mkdir(exist_ok=True)
    if ZIP.exists():
        ZIP.unlink()
    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(SITE.rglob("*")):
            if f.is_file():
                z.write(f, Path("nfl-edge-dashboard") / f.relative_to(SITE))
    print(f"Wrote {SITE.relative_to(ROOT)}/ and {ZIP.relative_to(ROOT)} ({ZIP.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
